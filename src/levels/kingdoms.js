export function getKingdomById(id) {
  return KINGDOMS.find((k) => k.id === id) || KINGDOMS[0];
}

export function getNextKingdomId(id) {
  const idx = KINGDOMS.findIndex((k) => k.id === id);
  if (idx >= 0 && idx + 1 < KINGDOMS.length) {
    return KINGDOMS[idx + 1].id;
  }
  return null;
}
