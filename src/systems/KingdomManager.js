export const TOTAL_CAMPAIGN_LEVELS = 1000;

export function getKingdomForLevel(levelNumber) {
  const lv = Math.max(1, Math.min(TOTAL_CAMPAIGN_LEVELS, Math.round(levelNumber || 1)));
  const kingdom =
    KINGDOM_DEFINITIONS.find((k) => lv >= k.startLevel && lv <= k.endLevel) ||
    KINGDOM_DEFINITIONS[0];
  const localIndex = lv - kingdom.startLevel + 1;
  const kingdomSpan = kingdom.endLevel - kingdom.startLevel + 1;
  const subBiomeIdx = Math.min(
    kingdom.subBiomes.length - 1,
    Math.floor(((localIndex - 1) / kingdomSpan) * kingdom.subBiomes.length)
  );
  return {
    kingdom,
    levelNumber: lv,
    localIndex,
    kingdomSpan,
    subBiome: kingdom.subBiomes[subBiomeIdx],
    isBossLevel: lv % 25 === 0 || lv === kingdom.endLevel,
    isMiniBossLevel: lv % 10 === 0 && lv % 25 !== 0 && lv !== kingdom.endLevel,
    isKingdomFinale: lv === kingdom.endLevel,
  };
}

export function getKingdomByDefId(id) {
  return KINGDOM_DEFINITIONS.find((k) => k.id === id) || KINGDOM_DEFINITIONS[0];
}
