export function getBonusWorldById(id) {
  return BONUS_WORLDS.find((b) => b.id === id) || BONUS_WORLDS[0];
}

export function isBonusWorldUnlocked(bonusWorld, saveData) {
  if (!bonusWorld) return false;
  if (bonusWorld.requiredCampaignLevel <= 1) return true;
  const unlockedList = saveData?.unlockedBonusWorlds || [];
  if (unlockedList.includes(bonusWorld.id)) return true;
  const highestLevel = saveData?.highestUnlockedLevel || 1;
  return highestLevel >= bonusWorld.requiredCampaignLevel;
}
