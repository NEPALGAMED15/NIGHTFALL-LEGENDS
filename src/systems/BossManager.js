export function getBossConfig(bossId, difficultyProfile = null) {
  const base = BOSS_DEFINITIONS[bossId] || BOSS_DEFINITIONS.root_warden;
  const hpScale = difficultyProfile?.hpScale || 1.0;
  const dmgScale = difficultyProfile?.dmgScale || 1.0;
  const speedScale = difficultyProfile?.speedScale || 1.0;

  return {
    ...base,
    maxHp: Math.round(base.baseHp * Math.min(2.6, hpScale)),
    damage: Math.round(base.damage * Math.min(1.85, dmgScale)),
    speed: Math.round(base.speed * Math.min(1.35, speedScale)),
  };
}
